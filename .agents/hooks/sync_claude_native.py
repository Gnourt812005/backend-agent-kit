#!/usr/bin/env python3
"""Generate Claude Code wiring (.claude/ and CLAUDE.md) from .agents/.

.agents/ stays the single source of truth:
  * core files in .agents/<path>
  * an optional stack pack in .agents/stacks/<pack>/<path> (set [stack] pack in
    kit.toml) that overrides the core file at the same <path> or adds new ones
  * per-project settings in .agents/kit.toml

Generated:
  .claude/commands/<name>.md   thin pointer to the resolved command file
  .claude/skills/<name>/SKILL.md  thin pointer, user-invocable: false
  .claude/agents/<name>.md     thin pointer, only for `subagent: true` agents
  .claude/rules/**.md          full copies with {layout} placeholders resolved,
                               so `paths:` frontmatter matches real directories
  CLAUDE.md                    imports AGENTS.md and .agents/CORE.md

.claude/settings.json is hand-maintained and never touched.
"""
import os
import re
import shutil
import sys

sys.dont_write_bytecode = True  # keep .agents/ free of __pycache__ (health check needs a clean tree)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import boundaries  # noqa: E402

ROOT = boundaries.KIT_ROOT
AGENTS = os.path.join(ROOT, ".agents")
CLAUDE = os.path.join(ROOT, ".claude")
HEADER = "<!-- GENERATED by .agents/hooks/sync-claude-native.sh — edit the .agents/ source and rerun the script. -->"


def frontmatter(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    fields = {}
    if m:
        for line in m.group(1).splitlines():
            km = re.match(r"^([\w-]+):\s*(.*)$", line)
            if km:
                fields[km.group(1)] = km.group(2).strip()
    return fields, text


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def collect(subdir, pattern, pack_dir):
    """Map item name -> resolved file, pack entries overriding core ones."""
    found = {}
    for base in [AGENTS] + ([pack_dir] if pack_dir else []):
        d = os.path.join(base, subdir)
        if not os.path.isdir(d):
            continue
        for entry in sorted(os.listdir(d)):
            path = os.path.join(d, entry, "SKILL.md") if pattern == "skill" else os.path.join(d, entry)
            if pattern == "skill" and os.path.isfile(path):
                found[entry] = path
            elif pattern == "md" and entry.endswith(".md") and os.path.isfile(path):
                found[entry[:-3]] = path
    return found


def collect_rules(pack_dir):
    found = {}
    for base in [AGENTS] + ([pack_dir] if pack_dir else []):
        d = os.path.join(base, "rules")
        for dp, _, fns in os.walk(d):
            for fn in fns:
                if fn.endswith(".md"):
                    p = os.path.join(dp, fn)
                    found[os.path.relpath(p, d)] = p
    return found


def main():
    raw = boundaries._parse_toml(os.path.join(AGENTS, "kit.toml")) if os.path.exists(os.path.join(AGENTS, "kit.toml")) else {}
    cfg = boundaries.load_config(ROOT)
    pack = (raw.get("stack", {}) or {}).get("pack", "") or ""
    pack_dir = os.path.join(AGENTS, "stacks", pack) if pack else None
    if pack_dir and not os.path.isdir(pack_dir):
        print(f"ERROR: [stack] pack = \"{pack}\" but {rel(pack_dir)}/ does not exist.", file=sys.stderr)
        return 2
    print(f"Stack pack: {pack or 'none (core only)'}")

    placeholders = {"source_root": cfg["source_root"], "tests": (raw.get("layout", {}) or {}).get("tests", "tests")}
    placeholders.update({k: v or k for k, v in cfg["layers"].items()})

    for sub in ("commands", "skills", "agents", "rules"):
        shutil.rmtree(os.path.join(CLAUDE, sub), ignore_errors=True)
        os.makedirs(os.path.join(CLAUDE, sub))

    # rules: full copies, placeholders resolved
    print("Generating .claude/rules/ ...")
    for rpath, src in sorted(collect_rules(pack_dir).items()):
        fields, text = frontmatter(src)
        for k, v in placeholders.items():
            text = text.replace("{" + k + "}", v.rstrip("/"))
        text = re.sub(r"^(---\n.*?\n---\n)", lambda m: m.group(1) + "\n" + HEADER.replace("the .agents/ source", rel(src)) + "\n", text, count=1, flags=re.S)
        out = os.path.join(CLAUDE, "rules", rpath)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            f.write(text)
        note = "" if "paths" in fields else "   WARNING: no paths: frontmatter, loads every session"
        print(f"  rules/{rpath} <- {rel(src)}{note}")

    print("Generating .claude/commands/ ...")
    for name, src in collect("commands", "md", pack_dir).items():
        fields, _ = frontmatter(src)
        with open(os.path.join(CLAUDE, "commands", name + ".md"), "w", encoding="utf-8") as f:
            f.write(f"---\ndescription: {fields.get('description', '')}\n---\n\n{HEADER}\n\n"
                    f"Follow the instructions in `{rel(src)}` exactly, step by step.\n")
        print(f"  /{name} -> {rel(src)}")

    print("Generating .claude/skills/ ...")
    for name, src in collect("skills", "skill", pack_dir).items():
        fields, _ = frontmatter(src)
        os.makedirs(os.path.join(CLAUDE, "skills", name))
        with open(os.path.join(CLAUDE, "skills", name, "SKILL.md"), "w", encoding="utf-8") as f:
            f.write(f"---\nname: {name}\ndescription: {fields.get('description', '')}\nuser-invocable: false\n---\n\n{HEADER}\n\n"
                    f"Follow the instructions in `{rel(src)}` exactly.\n")
        print(f"  skill {name} -> {rel(src)}")

    print("Generating .claude/agents/ (subagent: true only) ...")
    subagents = []
    for name, src in collect("agents", "md", pack_dir).items():
        fields, _ = frontmatter(src)
        if fields.get("subagent") != "true":
            continue
        subagents.append(name)
        with open(os.path.join(CLAUDE, "agents", name + ".md"), "w", encoding="utf-8") as f:
            f.write(f"---\nname: {name}\ndescription: {fields.get('description', '')}\ntools: {fields.get('tools', '')}\n---\n\n{HEADER}\n\n"
                    f"Read `{rel(src)}` for your full role, inputs, outputs, and checklist. Read every file listed under its \"## Inputs\" section before starting, and apply them exactly — do not invent additional rules.\n\n"
                    f"Report your result using that file's \"## Outputs\" and \"## Checklist\" sections as your contract.\n")
        print(f"  subagent {name} -> {rel(src)}")

    print("Generating CLAUDE.md ...")
    with open(os.path.join(ROOT, "CLAUDE.md"), "w", encoding="utf-8") as f:
        f.write(f"""@AGENTS.md
@.agents/CORE.md

{HEADER}

## Claude Code wiring

- Stack pack: {('`' + pack + '`') if pack else 'none'}. `/name` commands, skills, path-scoped rules and subagents ({', '.join('`' + s + '`' for s in subagents)}) are generated into `.claude/` from `.agents/`. Never hand-edit generated files.
- Hooks live in `.claude/settings.json` (hand-maintained, not generated).
""")
    print("Done.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
